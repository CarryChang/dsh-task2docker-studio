#!/usr/bin/env node
/**
 * Derive the portable Agent-Skill runtime from the compiled, DSH-free backend modules.
 *
 * `skills/dsh-task2docker-studio/` installs standalone into Claude Code / Cursor / Copilot (the open
 * Agent Skills format) with no DeepSeek Harness present. The dispatch logic lives once in `src/*.ts`;
 * after `tsc` it emits `lib/backend/{types,ssh,registry,engine}.js` — modules that import only Node
 * builtins and each other, never `@deepseek-ai`. This script copies exactly those compiled modules into
 * the skill's `scripts/lib/backend/`, preserving the directory so the relative imports still resolve,
 * and asserts no DSH or bare-package import slipped in. `src` stays the single source of truth.
 *
 * Run after `build`. Invoked from `check` and `prepack`; the result is committed so a GitHub clone or
 * a plain folder copy needs no build on the user's side.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const libDir = join(root, 'lib', 'backend')
const targetDir = join(root, 'skills', 'dsh-task2docker-studio', 'scripts', 'lib', 'backend')

/** Compiled backend modules the standalone CLI imports; each must stay DSH-free. */
const MODULES = ['types.js', 'ssh.js', 'registry.js', 'engine.js']

const header = [
  '/* Generated by scripts/build-portable.mjs from lib/backend (compiled from src/backend).',
  '   Edit src/backend/*.ts, run `pnpm run build && pnpm run build:portable`. Do not hand-edit. */',
  '',
].join('\n')

/**
 * Collect module specifiers from real import/export/require statements only. The patterns are anchored
 * so prose like `copy from "${name}"` inside a template string is not mistaken for a module dependency.
 * @param text - the compiled JavaScript source.
 * @returns the specifier strings.
 */
function specifiers(text) {
  const found = []
  const patterns = [
    /(?:^|[;\s])import\s+[^'";]*?from\s*['"]([^'"]+)['"]/g,
    /(?:^|[;\s])import\s*['"]([^'"]+)['"]/g,
    /(?:^|[;\s])export\s+[^'";]*?from\s*['"]([^'"]+)['"]/g,
    /\brequire\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
    /\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g,
  ]
  for (const pattern of patterns) {
    let match
    while ((match = pattern.exec(text)) !== null) {
      const raw = match[1]
      if (raw) found.push(raw)
    }
  }
  return found
}

mkdirSync(targetDir, { recursive: true })
for (const file of MODULES) {
  const source = join(libDir, file)
  let text
  try {
    text = readFileSync(source, 'utf8')
  } catch {
    throw new Error(`Missing ${source}; run \`pnpm run build\` before build:portable.`)
  }
  for (const spec of specifiers(text)) {
    const portable = spec.startsWith('.') || spec.startsWith('node:')
    if (!portable) {
      throw new Error(`lib/backend/${file} imports "${spec}"; the portable skill must stay dependency-free (no @deepseek-ai or bare packages).`)
    }
  }
  writeFileSync(join(targetDir, file), header + text)
}

console.log(`build:portable → skills/dsh-task2docker-studio/scripts/lib/backend/ {${MODULES.join(', ')}}`)
